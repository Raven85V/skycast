// (переименован из audio.h - на Windows совпадал по имени без
// учёта регистра с библиотечным Audio.h, что ломало #include <Audio.h>)
#pragma once
#include <Arduino.h>
#include <Audio.h> // schreibfaul1/ESP32-audioI2S

// ============================================================
// ОБЪЕДИНЁННЫЙ аудио-движок будильника И (будущего) веб-радио.
// Раньше будильник играл WAV через встроенный ESP_I2S (свой парсер
// заголовка), а радио должно было использовать эту же библиотеку
// отдельно. ОБЪЕДИНЕНО: теперь один и тот же движок Audio (schreibfaul1)
// обслуживает и то, и другое - будильник/ночь-утро играют локальные
// файлы с SD через connectToFile(), радио (модуль radio.cpp) будет
// дёргать connectToStream() того же объекта audio.
// Играть одновременно и то, и другое всё равно нельзя - один DAC,
// один I2S-выход - как и было задумано у автора оригинала (радио и
// обычный режим/будильник взаимоисключающие).
// ============================================================

// Инициализация SD-карты (SPI) и I2S-выхода на PCM5102, плюс сам
// аудио-движок. Вызывать один раз в setup(). Возвращает true, если
// SD-карта нашлась (звук будильника не будет работать без неё, но
// радио с интернет-потоков всё равно будет доступно).
bool initAudio();

// --- интерфейс для БУДИЛЬНИКА / ночь-утро (не менялся снаружи) ---

// Запускает воспроизведение файла с SD-карты (WAV/MP3/AAC/FLAC/...),
// например "/alarms/monday.wav". Останавливает то, что играло раньше.
void playAudioFile(const String &path);

// Немедленно останавливает воспроизведение (локальный файл ИЛИ поток).
void stopAudio();

// Играет ли что-то прямо сейчас (файл ИЛИ поток).
bool isAudioPlaying();

// Вызывать КАЖДУЮ итерацию loop() (не раз в секунду!) - библиотека
// стримит аудио порциями, без частых вызовов будут щелчки/заикания.
void audioLoop();

// --- интерфейс для будущего РАДИО-модуля (radio.cpp) ---

// Подключается к интернет-потоку по URL (http/https, mp3/aac/flac/...).
// Возвращает true, если запрос на подключение принят библиотекой
// (сам факт успешного проигрывания видно по audio_info_callback/логам).
bool connectToStream(const String &url);

// Громкость 0..21 (диапазон самой библиотеки).
void setAudioVolume(uint8_t volume);

// Прямой доступ к объекту библиотеки - на случай, если radio.cpp
// понадобятся более специфичные методы (getVUlevel, getBitrate и т.п.),
// не вынесенные в этот обёрточный интерфейс.
extern Audio audio;

// Позволяет radio.cpp подписаться на события библиотеки (название
// станции, текущий трек, битрейт и т.д.), не зная деталей логирования
// внутри audio.cpp. audio.cpp по-прежнему сам логирует всё в Serial -
// это ДОПОЛНИТЕЛЬНЫЙ коллбэк поверх встроенного логирования.
typedef void (*AudioEventCallback)(Audio::msg_t m);
void setAudioEventCallback(AudioEventCallback cb);
